package org.ledgerapi.domain;

/** Stable public error codes and their HTTP status (SRS section 4.3). */
public enum ErrorCode {
  VALIDATION_ERROR(400),
  INVALID_AMOUNT(400),
  MALFORMED_ID(400),
  MISSING_IDEMPOTENCY_KEY(400),
  INVALID_IDEMPOTENCY_KEY(400),
  UNSUPPORTED_CURRENCY(400),
  UNAUTHENTICATED(401),
  FORBIDDEN(403),
  NOT_FOUND(404),
  METHOD_NOT_ALLOWED(405),
  LOGIN_ALREADY_EXISTS(409),
  WALLET_ALREADY_EXISTS(409),
  ALREADY_REVERSED(409),
  PAYLOAD_TOO_LARGE(413),
  UNSUPPORTED_MEDIA_TYPE(415),
  INSUFFICIENT_FUNDS(422),
  CURRENCY_MISMATCH(422),
  SAME_WALLET_TRANSFER(422),
  BALANCE_LIMIT_EXCEEDED(422),
  NUMERIC_LIMIT_EXCEEDED(422),
  IDEMPOTENCY_KEY_REUSED(422),
  REVERSAL_NOT_ALLOWED(422),
  TOO_MANY_REQUESTS(429),
  INTERNAL_ERROR(500),
  STORAGE_BUSY(503),
  DATABASE_UNAVAILABLE(503);

  private final int httpStatus;

  ErrorCode(int httpStatus) {
    this.httpStatus = httpStatus;
  }

  public int httpStatus() {
    return httpStatus;
  }
}
